// Usage: node scripts/verify-hero.mjs <base> <outPrefix> <width> <height> <dsf>
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const [base, prefix, w = '1440', h = '860', dsf = '1'] = process.argv.slice(2);
const mobile = +w < 600;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: +dsf, isMobile: mobile, hasTouch: mobile });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`.slice(0, 300)); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
page.on('response', (r) => { if (r.status() >= 400) logs.push(`[${r.status()}] ${r.url()}`); });
await page.goto(base, { waitUntil: 'load' });
await page.waitForFunction(() => document.querySelector('.hero')?.dataset.ready === 'true', null, { timeout: 120000 });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${prefix}-intro.png` });
await page.waitForTimeout(9000);
await page.focus('.parts-index li:nth-child(13) button');
await page.waitForTimeout(4500);
await page.screenshot({ path: `${prefix}-balance.png` });
await page.focus('.parts-index li:nth-child(2) button');
await page.waitForTimeout(4500);
await page.screenshot({ path: `${prefix}-bezel.png` });
await page.evaluate(() => document.activeElement?.blur());
await page.evaluate(() => window.scrollTo(0, window.innerHeight * 1.15));
await page.waitForTimeout(5000);
await page.screenshot({ path: `${prefix}-closing.png` });
await page.evaluate(() => window.scrollTo(0, window.innerHeight * 2.3));
await page.waitForTimeout(5000);
await page.screenshot({ path: `${prefix}-closed.png` });
console.log([...new Set(logs)].slice(0, 20).join('\n') || 'no console errors');
await browser.close();
